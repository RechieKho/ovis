auto cmake_project_text(const project &p_project, const cmake_options &p_options)
    -> string_type {
  const auto root = std::filesystem::absolute(p_project.root).lexically_normal();
  // Said here, by the table's line, rather than by CMake about its file.
  for (const auto &dependency : p_project.c_dependencies) {
    const auto where = p_project.file.filename().string() + ", line " +
                       std::to_string(dependency.line) + ": [c." + dependency.name + "] ";
    std::error_code ignored;
    if (dependency.kind == c_dependency::kind_type::path &&
        !std::filesystem::exists(root / dependency.source / "CMakeLists.txt", ignored))
      throw error(where + "names " + dependency.source +
                  ", which is not a folder with a CMakeLists.txt in the project.");
    if (dependency.kind == c_dependency::kind_type::cmake &&
        !std::filesystem::is_regular_file(root / dependency.source, ignored))
      throw error(where + "names " + dependency.source +
                  ", which is not a file in the project.");
  }
  const auto name = p_project.program_name();
  std::ostringstream out;
  out << "# Generated by ovis from " << p_project.file.filename().string()
      << ". Don't edit: change ovis.toml, or the\n"
         "# files it names under `cmake`. `ovis cmake --print` shows it.\n"
         "cmake_minimum_required(VERSION 3.20)\n"
         "project("
      << cmake_quoted(name) << " LANGUAGES C)\n"
      << "set(OVIS_PROJECT_DIR " << cmake_quoted_path(root) << ")\n"
      << "set(OVIS_EXECUTABLE " << cmake_quoted_path(p_options.ovis_executable) << ")\n"
      << "include(\"${CMAKE_CURRENT_LIST_DIR}/OvisMacros.cmake\")\n\n";

  // The runtime, as find_package(Ovis) makes it: checked unless --fast.
  out << "add_library(ovis_runtime STATIC \"${CMAKE_CURRENT_LIST_DIR}/ovis_runtime.c\")\n"
         "set_target_properties(ovis_runtime PROPERTIES POSITION_INDEPENDENT_CODE ON "
         "C_STANDARD 11)\n"
         "target_link_libraries(ovis_runtime PUBLIC m)\n";
  if (!p_options.fast)
    out << "target_compile_definitions(ovis_runtime PRIVATE OVIS_CHECKED)\n";
  out << "add_library(ovis::runtime ALIAS ovis_runtime)\n\n";

  std::vector<string_type> links;
  std::vector<std::pair<string_type, const c_dependency *>> promised;
  bool pkg_config = false;
  bool fetching = false;
  // The author's own CMake files come last, so they may use the others.
  std::vector<const c_dependency *> ordered;
  for (const auto &dependency : p_project.c_dependencies)
    if (dependency.kind != c_dependency::kind_type::cmake)
      ordered.push_back(&dependency);
  for (const auto &dependency : p_project.c_dependencies)
    if (dependency.kind == c_dependency::kind_type::cmake)
      ordered.push_back(&dependency);
  for (const auto *const each : ordered) {
    const auto &dependency = *each;
    const auto table = "# [c." + dependency.name + "]\n";
    switch (dependency.kind) {
    case c_dependency::kind_type::pkg_config:
      if (!pkg_config)
        out << "find_package(PkgConfig REQUIRED)\n";
      pkg_config = true;
      out << table << "pkg_check_modules(" << identifier(dependency.name)
          << " REQUIRED IMPORTED_TARGET " << cmake_quoted(dependency.source) << ")\n";
      links.push_back("PkgConfig::" + identifier(dependency.name));
      break;
    case c_dependency::kind_type::git: {
      if (!fetching)
        out << "include(FetchContent)\n";
      fetching = true;
      const auto commit = p_options.commits.find(dependency.name);
      const auto &revision = commit != p_options.commits.end()
                                 ? commit->second
                                 : (dependency.commit.empty() ? dependency.tag
                                                              : dependency.commit);
      out << table << "FetchContent_Declare(" << identifier(dependency.name)
          << " GIT_REPOSITORY " << cmake_quoted(dependency.source) << "\n  GIT_TAG "
          << cmake_quoted(revision) << ")\n"
          << "FetchContent_MakeAvailable(" << identifier(dependency.name) << ")\n";
      break;
    }
    case c_dependency::kind_type::path:
      out << table << "add_subdirectory(" << cmake_quoted_path(root / dependency.source) << " "
          << identifier(dependency.name) << ")\n";
      break;
    case c_dependency::kind_type::cmake:
      out << table << "include(" << cmake_quoted_path(root / dependency.source) << ")\n";
      break;
    }
    for (const auto &target : dependency.targets) {
      links.push_back(target);
      promised.emplace_back(target, &dependency);
    }
  }
  // Every target ovis.toml promises, said where it went missing.
  for (const auto &[target, dependency] : promised)
    out << "if(NOT TARGET " << target << ")\n  message(FATAL_ERROR "
        << cmake_quoted(p_project.file.filename().string() + ", line " +
                  std::to_string(dependency->line) + ": [c." + dependency->name +
                  "] promises the target `" + target + "`, which " +
                  dependency->source + " doesn't define")
        << ")\nendif()\n";

  // The project's own C files: one library, with the [build] flags.
  const auto sources = c_source_files(p_project);
  if (!sources.empty()) {
    const auto library = identifier(name) + "_files";
    out << "\n# c = [...]\nadd_library(" << library << " STATIC";
    for (const auto &source : sources)
      out << "\n  " << cmake_quoted_path(source);
    out << ")\n";
    for (const auto &directory : p_project.include)
      out << "target_include_directories(" << library << " PUBLIC "
          << cmake_quoted_path(root / directory) << ")\n";
    for (const auto &define : p_project.defines)
      out << "target_compile_definitions(" << library << " PUBLIC " << cmake_quoted(define)
          << ")\n";
    for (const auto &link : links)
      out << "target_link_libraries(" << library << " PUBLIC " << link << ")\n";
    links.insert(links.begin(), library);
  }

  out << "\n# The program: settled as `ovis run` does unless --locked.\n";
  out << "set(OVIS_UNLOCKED " << (p_options.unlocked ? "ON" : "OFF") << ")\n";
  out << "set(OVIS_FAST " << (p_options.fast ? "ON" : "OFF") << ")\n";
  out << "set(OVIS_FLAGS";
  for (const auto &directory : p_project.phrases)
    out << " --phrases " << cmake_quoted_path(root / directory);
  for (const auto &flag : p_options.ovis_flags)
    out << " " << cmake_quoted(flag);
  out << ")\n";
  out << "ovis_add_executable(" << cmake_quoted(name) << " " << cmake_quoted_path(root);
  if (!links.empty()) {
    out << " LINK";
    for (const auto &link : links)
      out << " " << link;
  }
  out << " USE_LINKS)\n";
  for (const auto &directory : p_project.include)
    out << "target_include_directories(" << cmake_quoted(name) << " PRIVATE "
        << cmake_quoted_path(root / directory) << ")\n";
  for (const auto &define : p_project.defines)
    out << "target_compile_definitions(" << cmake_quoted(name) << " PRIVATE "
        << cmake_quoted(define) << ")\n";
  return out.str();
}

auto write_cmake_project(const project &p_project, const cmake_options &p_options,
                         const std::filesystem::path &p_build_directory)
    -> std::filesystem::path {
  const auto source = p_build_directory / "cmake";
  std::filesystem::create_directories(source);
  write_if_changed(source / "OvisMacros.cmake", embedded_ovis_macros());
  write_if_changed(source / "ovis_runtime.c", codegen::runtime_source());
  write_if_changed(source / "CMakeLists.txt", cmake_project_text(p_project, p_options));
  return source;
}

auto build_with_cmake(const project &p_project, const cmake_options &p_options,
                      const std::filesystem::path &p_build_directory,
                      bool p_verbose) -> std::filesystem::path {
  const auto source = write_cmake_project(p_project, p_options, p_build_directory);
  const auto binary = p_build_directory / "cmake-build";

  const auto log = p_build_directory / "cmake.log";
  std::filesystem::remove(log);
  const auto failed = [&](const char *p_what) -> error {
    auto text = read_text(log);
    // The end says what went wrong; the start is CMake's greeting.
    if (text.size() > 6000)
      text = "…\n" + text.substr(text.size() - 6000);
    return error(string_type("CMake failed to ") + p_what + " the project generated from " +
                 p_project.file.filename().string() + " (" + source.string() +
                 "; `ovis cmake --print` shows it):\n" + text);
  };
  // CMake configures again by itself when CMakeLists.txt changes, once a
  // configure has finished (check_cache is written last).
  if (!std::filesystem::exists(binary / "CMakeFiles" / "cmake.check_cache") &&
      !run_logged("cmake", {"-S", source.string(), "-B", binary.string(),
                            "-DCMAKE_BUILD_TYPE=Release"},
                  log, p_verbose))
    throw failed("configure");
  if (!run_logged("cmake", {"--build", binary.string()}, log, p_verbose))
    throw failed("build");
  return binary / p_project.program_name();
}

