// A CMake bracket argument: no escapes, whatever the text holds.
auto cmake_quoted(string_view_type p_text) -> string_type {
  string_type equals = "=";
  while (string_view_type(p_text).find("]" + equals + "]") != string_view_type::npos)
    equals += "=";
  return "[" + equals + "[" + string_type(p_text) + "]" + equals + "]";
}

auto cmake_quoted_path(const std::filesystem::path &p_path) -> string_type {
  return cmake_quoted(p_path.generic_string());
}

// A CMake identifier from a table's name (`c.my-lib` → ovis_c_my_lib).
auto identifier(string_view_type p_name) -> string_type {
  string_type result = "ovis_c_";
  for (const auto character : p_name)
    result.push_back(std::isalnum(static_cast<unsigned char>(character))
                         ? character
                         : '_');
  return result;
}

auto read_text(const std::filesystem::path &p_path) -> string_type {
  std::ifstream input(p_path);
  std::stringstream text;
  text << input.rdbuf();
  return text.str();
}

// Writes the file only if its text changed, so its time says when it did.
auto write_if_changed(const std::filesystem::path &p_path, string_view_type p_text)
    -> void {
  std::error_code ignored;
  if (std::filesystem::exists(p_path, ignored) && read_text(p_path) == p_text)
    return;
  std::ofstream output(p_path);
  output << p_text;
  if (!output)
    throw error("Can't write " + p_path.string() + ".");
}

// Runs a program with its output in `p_log`; true when it succeeded.
auto run_logged(const string_type &p_program, const std::vector<string_type> &p_arguments,
                const std::filesystem::path &p_log, bool p_verbose) -> bool {
  const auto found = llvm::sys::findProgramByName(p_program);
  if (!found)
    throw error("This project's C dependencies are built with CMake, which is not "
                "installed (cmake 3.20 or later; `ovisup check` says what else is "
                "missing).");
  std::vector<llvm::StringRef> arguments = {*found};
  for (const auto &argument : p_arguments)
    arguments.push_back(argument);
  if (p_verbose)
    return llvm::sys::ExecuteAndWait(*found, arguments) == 0;
  const auto log = p_log.string();
  const std::optional<llvm::StringRef> redirects[] = {
      llvm::StringRef(), llvm::StringRef(log), llvm::StringRef(log)};
  return llvm::sys::ExecuteAndWait(*found, arguments, std::nullopt, redirects) == 0;
}

